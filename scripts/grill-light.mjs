// The firelight curve of the hero's grill film (src/components/fx/grillLight.ts): how bright the
// film is at each moment, measured exactly as the scene used to measure it live (the frame drawn
// into a 16 x 9 canvas and averaged), so the scene can look it up instead of reading the video
// back from the GPU every few frames. Run again whenever public/video/grill.mp4 changes:
//
//   PLAYWRIGHT=<path to playwright-core> node scripts/grill-light.mjs
//
// Needs Google Chrome (H.264). Nothing is served; the script exits by itself.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHROME = process.env.CHROME || "C:/Program Files/Google/Chrome/Application/chrome.exe";
const STEP = 25; // samples a second
const { chromium } = await import(pathToFileURL(createRequire(import.meta.url).resolve(process.env.PLAYWRIGHT || "playwright"))).then((m) => m.default ?? m);
setTimeout(() => (console.error("timed out"), process.exit(3)), 180000).unref();

const film = fs.readFileSync(path.join(ROOT, "public/video/grill.mp4"));
const browser = await chromium.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage();
await page.route("**/*", (route) => {
  const p = new URL(route.request().url()).pathname;
  if (p === "/") return route.fulfill({ body: "<!doctype html><body>", headers: { "content-type": "text/html" } });
  const range = /bytes=(\d*)-(\d*)/.exec(route.request().headers().range || "");
  if (!range) return route.fulfill({ body: film, headers: { "content-type": "video/mp4", "accept-ranges": "bytes" } });
  const start = +range[1] || 0;
  const end = range[2] ? +range[2] : film.length - 1;
  return route.fulfill({ status: 206, body: film.subarray(start, end + 1), headers: { "content-type": "video/mp4", "accept-ranges": "bytes", "content-range": `bytes ${start}-${end}/${film.length}` } });
});
await page.goto("http://grill.local/");
const { duration, values } = await page.evaluate(async (step) => {
  const video = document.createElement("video");
  video.muted = true;
  video.preload = "auto";
  video.src = "/film.mp4";
  await new Promise((ok) => video.addEventListener("loadeddata", ok, { once: true }));
  const probe = document.createElement("canvas");
  probe.width = 16;
  probe.height = 9;
  const ctx = probe.getContext("2d", { willReadFrequently: true });
  const values = [];
  for (let i = 0; i < Math.floor(video.duration * step); i++) {
    await new Promise((ok) => {
      video.addEventListener("seeked", ok, { once: true });
      video.currentTime = i / step;
    });
    ctx.drawImage(video, 0, 0, 16, 9);
    const d = ctx.getImageData(0, 0, 16, 9).data;
    let s = 0;
    for (let j = 0; j < d.length; j += 4) s += d[j] * 0.5 + d[j + 1] * 0.4 + d[j + 2] * 0.1;
    values.push(s / (d.length / 4) / 255);
  }
  return { duration: video.duration, values };
}, STEP);
await browser.close();

const out = `// Generated by scripts/grill-light.mjs from public/video/grill.mp4 (${duration.toFixed(2)} s): don't edit by hand.
/** How bright the grill film is (0..1), ${STEP} times a second. */
export const GRILL_LIGHT = { step: ${STEP}, duration: ${duration.toFixed(3)}, values: [${values.map((v) => v.toFixed(3).replace(/^0/, "")).join(",")}] };
`;
fs.writeFileSync(path.join(ROOT, "src/components/fx/grillLight.ts"), out);
console.log(values.length, "samples, range", Math.min(...values).toFixed(3), "-", Math.max(...values).toFixed(3));
process.exit(0);
